-- ============================================================================
-- สถานที่ส่งข้าวห่อ (ข้อมูลกลางสำหรับทุกเครื่อง)
--
--   READ          ผู้ใช้ทั่วไปและแอดมินอ่านรายการของโครงการได้
--   CREATE/UPDATE/DELETE  ทำผ่าน RPC ที่ตรวจ PIN แอดมินจาก app_config เท่านั้น
--
-- ประวัติ food_orders เก็บชื่อสถานที่เป็นข้อความ จึงไม่ถูกเปลี่ยนหรือลบตาม
-- การแก้ไขรายการตั้งค่านี้
--
-- รันหลัง 01–10 (รันซ้ำได้)
-- ============================================================================

create table if not exists public.delivery_points (
  id bigint generated by default as identity primary key,
  project text not null,
  name text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint delivery_points_project_name_key unique (project, name),
  constraint delivery_points_project_not_blank check (btrim(project) <> ''),
  constraint delivery_points_name_not_blank check (btrim(name) <> ''),
  constraint delivery_points_name_length check (char_length(btrim(name)) <= 80)
);

comment on table public.delivery_points is 'รายการสถานที่ส่งข้าวห่อที่แอดมินโรงครัวจัดการ แยกตามโครงการ';
comment on column public.delivery_points.name is 'ชื่อที่แสดงในช่อง ส่งห่อที่; การเปลี่ยนชื่อไม่กระทบ food_orders ย้อนหลัง';

create unique index if not exists delivery_points_project_name_ci_key
  on public.delivery_points (project, lower(btrim(name)));

create index if not exists delivery_points_project_sort_idx
  on public.delivery_points (project, sort_order, id);

alter table public.delivery_points enable row level security;

drop policy if exists delivery_points_read on public.delivery_points;
create policy delivery_points_read
  on public.delivery_points
  for select
  to anon, authenticated
  using (true);

revoke all on public.delivery_points from anon, authenticated;
grant select (id, project, name, sort_order, created_at, updated_at)
  on public.delivery_points to anon, authenticated;

