with seed(project, name, sort_order) as (
  values
    ('xepon',  'KeepRoom ตู้เหลือง', 10),
    ('xepon',  'KeepRoom ตู้ขาว',    20),
    ('xepon',  'หน้างาน',             30),
    ('xepon',  'แคมป์ที่พัก',          40),
    ('sekong', 'KeepRoom ตู้เหลือง', 10),
    ('sekong', 'KeepRoom ตู้ขาว',    20),
    ('sekong', 'หน้างาน',             30),
    ('sekong', 'แคมป์ที่พัก',          40)
)
insert into public.delivery_points (project, name, sort_order)
select seed.project, seed.name, seed.sort_order
  from seed
 where not exists (
   select 1
     from public.delivery_points current
    where current.project = seed.project
      and lower(btrim(current.name)) = lower(btrim(seed.name))
 );

-- ---------------------------------------------------------------------------
-- เพิ่มสถานที่ส่ง
-- ---------------------------------------------------------------------------
create or replace function public.create_delivery_point(
  p_project text,
  p_name text,
  p_admin_pin text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project text := lower(btrim(coalesce(p_project, '')));
  v_name text := btrim(coalesce(p_name, ''));
  v_admin_pin text;
  v_sort_order integer;
  v_row public.delivery_points;
begin
  select value into v_admin_pin from public.app_config where key = 'admin_pin';
  if v_admin_pin is null or coalesce(p_admin_pin, '') <> v_admin_pin then
    raise exception 'รหัสแอดมินไม่ถูกต้อง';
  end if;
  if v_project = '' then
    raise exception 'กรุณาระบุโครงการ';
  end if;
  if v_name = '' then
    raise exception 'กรุณากรอกชื่อสถานที่ส่ง';
  end if;
  if char_length(v_name) > 80 then
    raise exception 'ชื่อสถานที่ส่งต้องไม่เกิน 80 ตัวอักษร';
  end if;
  if exists (
    select 1 from public.delivery_points
     where project = v_project and lower(btrim(name)) = lower(v_name)
  ) then
    raise exception 'มีสถานที่ส่ง % อยู่ในรายการแล้ว', v_name;
  end if;

  select coalesce(max(sort_order), 0) + 10
    into v_sort_order
    from public.delivery_points
   where project = v_project;

  insert into public.delivery_points (project, name, sort_order)
  values (v_project, v_name, v_sort_order)
  returning * into v_row;

  return to_jsonb(v_row);
end;
$$;

-- ---------------------------------------------------------------------------
-- เปลี่ยนชื่อสถานที่ส่ง — ไม่แก้ food_orders ย้อนหลัง
-- ---------------------------------------------------------------------------
create or replace function public.rename_delivery_point(
  p_project text,
  p_current_name text,
  p_new_name text,
  p_admin_pin text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project text := lower(btrim(coalesce(p_project, '')));
  v_current_name text := btrim(coalesce(p_current_name, ''));
  v_new_name text := btrim(coalesce(p_new_name, ''));
  v_admin_pin text;
  v_id bigint;
  v_row public.delivery_points;
begin
  select value into v_admin_pin from public.app_config where key = 'admin_pin';
  if v_admin_pin is null or coalesce(p_admin_pin, '') <> v_admin_pin then
    raise exception 'รหัสแอดมินไม่ถูกต้อง';
  end if;
  if v_project = '' or v_current_name = '' then
    raise exception 'กรุณาระบุโครงการและสถานที่เดิม';
  end if;
  if v_new_name = '' then
    raise exception 'กรุณากรอกชื่อสถานที่ส่งใหม่';
  end if;
  if char_length(v_new_name) > 80 then
    raise exception 'ชื่อสถานที่ส่งต้องไม่เกิน 80 ตัวอักษร';
  end if;

  select id into v_id
    from public.delivery_points
   where project = v_project
     and lower(btrim(name)) = lower(v_current_name);

  if v_id is null then
    raise exception 'ไม่พบสถานที่ส่ง %', v_current_name;
  end if;
  if exists (
    select 1 from public.delivery_points
     where project = v_project
       and lower(btrim(name)) = lower(v_new_name)
       and id <> v_id
  ) then
    raise exception 'มีสถานที่ส่ง % อยู่ในรายการแล้ว', v_new_name;
  end if;

  update public.delivery_points
     set name = v_new_name, updated_at = now()
   where id = v_id
  returning * into v_row;

  return to_jsonb(v_row);
end;
$$;

-- ---------------------------------------------------------------------------
-- ลบสถานที่ส่ง — ไม่ลบหรือแก้ food_orders ย้อนหลัง
-- ---------------------------------------------------------------------------
create or replace function public.delete_delivery_point(
  p_project text,
  p_name text,
  p_admin_pin text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project text := lower(btrim(coalesce(p_project, '')));
  v_name text := btrim(coalesce(p_name, ''));
  v_admin_pin text;
  v_deleted integer;
begin
  select value into v_admin_pin from public.app_config where key = 'admin_pin';
  if v_admin_pin is null or coalesce(p_admin_pin, '') <> v_admin_pin then
    raise exception 'รหัสแอดมินไม่ถูกต้อง';
  end if;
  if v_project = '' or v_name = '' then
    raise exception 'กรุณาระบุโครงการและสถานที่ส่ง';
  end if;

  delete from public.delivery_points
   where project = v_project
     and lower(btrim(name)) = lower(v_name);
  get diagnostics v_deleted = row_count;

  if v_deleted = 0 then
    raise exception 'ไม่พบสถานที่ส่ง %', v_name;
  end if;

  return jsonb_build_object(
    'project', v_project,
    'name', v_name,
    'deleted', v_deleted
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- สิทธิ์เรียก RPC
-- ---------------------------------------------------------------------------
revoke all on function public.create_delivery_point(text, text, text) from public;
revoke all on function public.rename_delivery_point(text, text, text, text) from public;
revoke all on function public.delete_delivery_point(text, text, text) from public;

grant execute on function public.create_delivery_point(text, text, text) to anon, authenticated;
grant execute on function public.rename_delivery_point(text, text, text, text) to anon, authenticated;
grant execute on function public.delete_delivery_point(text, text, text) to anon, authenticated;

-- ตรวจผล
select project, name, sort_order
  from public.delivery_points
 order by project, sort_order, id;
